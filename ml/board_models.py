"""The two 8-bit models for the board's AI chip (Ethos-U55), as C arrays for the firmware.

    ../ml-env/bin/python -m ml.board_models

Compiles ml/data/models/{breath_slot,state}_int8.tflite with Arm's Vela compiler for the
Ethos-U55 (128 MACs, as Infineon's DEEPCRAFT tools build for this chip) and writes
firmware/proj_cm55/ibuki/models/ibuki_models.{c,h}. That folder is not in git: the weights
come partly from AIR-400, whose data has no stated license (see ml/README.md). Without it the
firmware still builds; it just doesn't run the models (firmware/proj_cm55/ibuki/ai.c).
"""
from __future__ import annotations

import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
MODELS = REPO / "ml" / "data" / "models"
VELA_OUT = REPO / "ml" / "data" / "vela"
C_DIR = REPO / "firmware" / "proj_cm55" / "ibuki" / "models"
NAMES = {"breath_slot": "ibuki_breath_model", "state": "ibuki_state_model"}


def vela(name: str) -> Path:
    VELA_OUT.mkdir(parents=True, exist_ok=True)
    vela_bin = Path(sys.executable).parent / "vela"
    subprocess.run([str(vela_bin), str(MODELS / f"{name}_int8.tflite"), "--accelerator-config",
                    "ethos-u55-128", "--output-dir", str(VELA_OUT)], check=True,
                   stdout=subprocess.DEVNULL)
    return VELA_OUT / f"{name}_int8_vela.tflite"


def c_array(sym: str, data: bytes) -> str:
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    # in SoC memory and 16-byte aligned, like Infineon's CY_ML_MODEL_MEM, so the NPU can read it
    return (f"__attribute__((section(\".cy_socmem_data\"), aligned(16)))\n"
            f"const uint8_t {sym}[{len(data)}] = {{\n    " + ",\n    ".join(rows) + "\n};\n"
            f"const unsigned int {sym}_len = {len(data)}U;\n")


def main():
    C_DIR.mkdir(parents=True, exist_ok=True)
    body, head = [], []
    for name, sym in NAMES.items():
        data = vela(name).read_bytes()
        body.append(c_array(sym, data))
        head.append(f"extern const uint8_t {sym}[{len(data)}];\nextern const unsigned int {sym}_len;\n")
        print(f"{name}: {len(data)} bytes for the Ethos-U55")
    note = "/* Generated by ml/board_models.py from the trained models. Not in git. */\n"
    (C_DIR / "ibuki_models.h").write_text(note + "#ifndef IBUKI_MODELS_H\n#define IBUKI_MODELS_H\n#include <stdint.h>\n"
                                          + "".join(head) + "#endif\n")
    (C_DIR / "ibuki_models.c").write_text(note + '#include "ibuki_models.h"\n\n' + "\n".join(body))


if __name__ == "__main__":
    main()
